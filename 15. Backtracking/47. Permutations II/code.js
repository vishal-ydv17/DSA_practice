/**
 * @param {number[]} nums
 * @return {number[][]}
 */
//LOGIC-Sort nums first so duplicates sit adjacent and at each node skip a choice if it matches the one
//right before it in the current choices array (avoids regenerating a permutation already made from this node) and otherwise pick it and recurse with a new choices array that has that element sliced out
//so nothing gets reused within a branch. Once path is as long as nums its a complete unique permutation
//so save it
var permuteUnique = function(nums) {
    let ans=[];
    nums.sort((a, b) => a - b); 

    var backtrack=(path, choices)=>{
        // base case
        if(path.length===nums.length){
            ans.push([...path]);
            return;
        }

        for(let i=0; i<choices.length; i++){
            // skip duplicate values sitting adjacent in the CURRENT choices array —
            // using the same value twice at this position would just recreate
            // a permutation already generated by an earlier iteration
            if (i > 0 && choices[i] === choices[i - 1]){
                continue;
            }
            path.push(choices[i]);
            // recurse with a NEW choices array: everything except the picked index i
            // (this removes it so it can't be reused further down this branch)
            backtrack(path, [...choices.slice(0,i), ...choices.slice(i+1)]);
            path.pop();
        }
    }
    backtrack([], nums);
    return ans;
};